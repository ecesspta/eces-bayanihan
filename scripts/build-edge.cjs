'use strict';
/* Bundles the school rules, storage and entry file into ONE file for Supabase: supabase/functions/eces/index.ts
   Paste that file into Supabase > Edge Functions > Deploy a new function > Via Editor. */
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const files = {
  '../dist/examples.js': 'dist/examples.js',
  '../dist/workflows.js': 'dist/workflows.js',
  '../backend/core.cjs': 'backend/core.cjs',
  '../backend/postgres-store.cjs': 'backend/postgres-store.cjs',
  '../backend/translate.cjs': 'backend/translate.cjs'
};
const names = {
  './examples.js': '../dist/examples.js'
};
let out = '// @ts-nocheck\n// ECES Bayanihan server function. Generated by scripts/build-edge.cjs. Do not edit by hand.\n';
const entry = fs.readFileSync(path.join(root, 'supabase/entry.js'), 'utf8');
// Imports first (ES modules must keep them at the top).
const imports = entry.split('\n').filter(l => /^import /.test(l));
out += imports.join('\n') + '\n';
out += "import { randomBytes as __rb, createHash as __ch, scryptSync as __sc, timingSafeEqual as __te } from 'node:crypto';\n";
out += 'globalThis.Buffer = Buffer;\n';
out += 'globalThis.__SAMPLE_SHEET = ' + JSON.stringify(fs.readFileSync(path.join(root, 'dist/assets/sample-collection-sheet.pdf')).toString('base64')) + ';\n';
out += 'const __defs = {};\nconst __cache = {};\n';
out += "const require = id => { const k = __alias[id] || id; if (k === 'node:crypto') return { randomBytes: __rb, createHash: __ch, scryptSync: __sc, timingSafeEqual: __te }; if (!__cache[k]) { const m = { exports: {} }; __cache[k] = m; __defs[k](m, m.exports, require); } return __cache[k].exports; };\n";
out += 'const __alias = ' + JSON.stringify({
  './examples.js': '../dist/examples.js'
}) + ';\n';
for (const [key, rel] of Object.entries(files)) {
  const src = fs.readFileSync(path.join(root, rel), 'utf8');
  out += '__defs[' + JSON.stringify(key) + '] = (module, exports, require) => {\n' + src + '\n};\n';
}
const body = entry.split('\n').filter(l => !/^import /.test(l) && !/^globalThis\.Buffer/.test(l)).join('\n');
out += body;
const dir = path.join(root, 'supabase/functions/eces');
fs.mkdirSync(dir, {
  recursive: true
});
fs.writeFileSync(path.join(dir, 'index.ts'), out);
console.log('supabase/functions/eces/index.ts', (out.length / 1024).toFixed(0) + ' KB');
